// Scope APIs that are the framework's own APIs, only typed against the
// scope's router.
const frameworkScopeApis = new Set<string>([
  'useMatches',
  'useParentMatches',
  'useChildMatches',
  'useLocation',
  'useRouterState',
  'useBlocker',
])

// Id-based scope APIs. Only the namespace of one installation of a module
// installed several times (`<moduleId>#<as>`) maps the module's route ids to
// that installation; every other scope uses the framework's own APIs.
const idScopeApis = new Set<string>([
  'getRouteApi',
  'useMatch',
  'useLoaderData',
  'useLoaderDeps',
  'useSearch',
  'useParams',
  'useRouteContext',
  'notFound',
])

function scopeBindings(
  frameworkPackage: string,
  routerType: string,
  key: string,
) {
  const capitalized = (api: string) => api[0]!.toUpperCase() + api.slice(1)
  // Exporting the framework's API itself costs no runtime binding.
  const isFrameworkApi = (api: string) =>
    frameworkScopeApis.has(api) || (idScopeApis.has(api) && !key.includes('#'))
  const frameworkApis = scopeApis.filter(isFrameworkApi)
  const boundApis = scopeApis.filter((api) => !isFrameworkApi(api))
  return [
    `import { ${boundApis.map((api) => `bindRouteScope${capitalized(api)}`).join(', ')} } from '${frameworkPackage}/_internal/route-module'`,
    `import { ${frameworkApis.map((api) => `${api} as framework${capitalized(api)}`).join(', ')} } from '${frameworkPackage}'`,
    `import type { RouteScope } from '${frameworkPackage}'`,
    ...scopeApis.map(
      (api) =>
        `export const ${api}: RouteScope<${routerType}>['${api}'] = ${
          isFrameworkApi(api)
            ? `framework${capitalized(api)} as never`
            : `/* @__PURE__ */ bindRouteScope${capitalized(api)}<${routerType}>('${key}')`
        }`,
    ),
    `import type { ValidateLinkOptions as RouterValidateLinkOptions, ValidateLinkOptionsArray as RouterValidateLinkOptionsArray, ValidateNavigateOptions as RouterValidateNavigateOptions, ValidateNavigateOptionsArray as RouterValidateNavigateOptionsArray, ValidateRedirectOptions as RouterValidateRedirectOptions, ValidateRedirectOptionsArray as RouterValidateRedirectOptionsArray, ValidateFromPath as RouterValidateFromPath, ValidateToPath as RouterValidateToPath, ValidateSearch as RouterValidateSearch, ValidateParams as RouterValidateParams, ValidateId as RouterValidateId, ValidateUseSearchOptions as RouterValidateUseSearchOptions, ValidateUseParamsOptions as RouterValidateUseParamsOptions } from '${frameworkPackage}'`,
    `export type ValidateLinkOptions<TOptions = unknown, TDefaultFrom extends string = string, TComp = 'a'> = RouterValidateLinkOptions<${routerType}, TOptions, TDefaultFrom, TComp>`,
    `export type ValidateLinkOptionsArray<TOptions extends ReadonlyArray<any> = ReadonlyArray<unknown>, TDefaultFrom extends string = string, TComp = 'a'> = RouterValidateLinkOptionsArray<${routerType}, TOptions, TDefaultFrom, TComp>`,
    `export type ValidateNavigateOptions<TOptions = unknown, TDefaultFrom extends string = string> = RouterValidateNavigateOptions<${routerType}, TOptions, TDefaultFrom>`,
    `export type ValidateNavigateOptionsArray<TOptions extends ReadonlyArray<any> = ReadonlyArray<unknown>, TDefaultFrom extends string = string> = RouterValidateNavigateOptionsArray<${routerType}, TOptions, TDefaultFrom>`,
    `export type ValidateRedirectOptions<TOptions = unknown, TDefaultFrom extends string = string> = RouterValidateRedirectOptions<${routerType}, TOptions, TDefaultFrom>`,
    `export type ValidateRedirectOptionsArray<TOptions extends ReadonlyArray<any> = ReadonlyArray<unknown>, TDefaultFrom extends string = string> = RouterValidateRedirectOptionsArray<${routerType}, TOptions, TDefaultFrom>`,
    `export type ValidateFromPath<TFrom = string> = RouterValidateFromPath<${routerType}, TFrom>`,
    `export type ValidateToPath<TTo extends string | undefined = undefined, TFrom extends string = string> = RouterValidateToPath<${routerType}, TTo, TFrom>`,
    `export type ValidateSearch<TTo extends string | undefined = undefined, TFrom extends string = string> = RouterValidateSearch<${routerType}, TTo, TFrom>`,
    `export type ValidateParams<TTo extends string | undefined = undefined, TFrom extends string = string> = RouterValidateParams<${routerType}, TTo, TFrom>`,
    `export type ValidateId<TId extends string = string> = RouterValidateId<${routerType}, TId>`,
    `export type ValidateUseSearchOptions<TOptions> = RouterValidateUseSearchOptions<TOptions, ${routerType}>`,
    `export type ValidateUseParamsOptions<TOptions> = RouterValidateUseParamsOptions<TOptions, ${routerType}>`,
  ]
}

function scopeMatchGuard(
  frameworkPackage: string,
  routerType: string,
  matchRoots: Array<string>,
) {
  // Every route id of a module starts with its root id, `<module>:` or
  // `<module>#<installation>:`, and package names contain no colon. Checking
  // these prefixes instead of listing every route keeps the guard small and
  // accepts routes a module adds after this scope was generated. Explicitly
  // named installations check their final identity. Local provider routes
  // accept any installation of that provider, using the stable local id.
  const local = matchRoots.filter((root) => !root.includes('#'))
  const installed = matchRoots.filter((root) => root.includes('#'))
  const checks = [
    ...local.map((root) => `localRouteId.startsWith(${JSON.stringify(root)})`),
    ...installed.map(
      (root) => `match.routeId.startsWith(${JSON.stringify(root)})`,
    ),
  ]
  return [
    `import type { AnyRouteMatch, KnownRouteMatchUnion } from '${frameworkPackage}'`,
    `/** Narrows a full router match to the routes installed in this scope. */
export function isScopedMatch(match: AnyRouteMatch): match is KnownRouteMatchUnion<${routerType}> {
  ${local.length ? "const localRouteId = match.localRouteId ?? ''\n  " : ''}return ${checks.length ? checks.join(' || ') : 'false'}
}`,
  ]
}

/** One generated namespace, as passed to a `routeScopeNamespaceFiles` function. */
export interface RouteScopeNamespace {
  /** The namespace's identifier in the scope, such as `products`. */
  name: string
  /** The id of the module it addresses. */
  moduleId: string
  /** The module id, or `<moduleId>#<as>` for one installation of a module. */
  key: string
  /** Its position among the scope's namespaces, ordered by key. */
  index: number
}

/**
 * Where the generated files of route-module namespaces live:
 * - `'indexed'`: `routeScope.gen.namespace<N>.ts` next to the route tree;
 * - `'named'`: `routeScope.gen.<namespace>.ts` next to the route tree;
 * - `'folder'`: `routeScope.gen/<namespace>.ts`;
 * - a function returning the path relative to the generated route tree's
 *   directory, without extension.
 */
export type RouteScopeNamespaceFiles =
  | 'indexed'
  | 'named'
  | 'folder'
  | RouteScopeNamespaceFile

/** Returns the file of a namespace, relative to the generated route tree's directory and without extension. */
export type RouteScopeNamespaceFile = (namespace: RouteScopeNamespace) => string

const reservedFiles = [
  ROUTE_SCOPE_FILE,
  ROUTE_CONTRACT_FILE,
  ROUTE_MODULE_FILE,
  START_MODULES_FILE,
]

/** The client view of the route tree, next to it. */
export function getClientRouteTreeFile(routeTreeFile: string) {
  return `${routeTreeFile}.client`
}

/**
 * The file of each namespace of the scope (by key), relative to the generated
 * route tree's directory and without extension.
 */
export function getRouteNamespaceFiles(
  context: RouteModuleContext,
  layout: RouteScopeNamespaceFiles,
  routeTreeFile: string,
): Map<string, string> {
  const keys = context.scope.map((entry) => entry.key).sort()
  const files = new Map<string, string>()
  // Namespace files are distinct ignoring case, so they are portable to
  // case-insensitive filesystems.
  const taken = new Map(
    [
      ...reservedFiles,
      routeTreeFile,
      getClientRouteTreeFile(routeTreeFile),
    ].map((file) => [file.toLowerCase(), file]),
  )
  for (const module of context.scope) {
    const index = keys.indexOf(module.key)
    const file = path.posix.normalize(
      replaceBackslash(
        layout === 'indexed'
          ? `${ROUTE_SCOPE_FILE}.namespace${index}`
          : layout === 'named'
            ? `${ROUTE_SCOPE_FILE}.${module.namespace}`
            : layout === 'folder'
              ? `${ROUTE_SCOPE_FILE}/${module.namespace}`
              : layout({
                  name: module.namespace,
                  moduleId: module.moduleId,
                  key: module.key,
                  index,
                }),
      ),
    )
    if (
      !file ||
      file === '.' ||
      path.posix.isAbsolute(file) ||
      path.win32.isAbsolute(file) ||
      file === '..' ||
      file.startsWith('../')
    ) {
      throw new Error(
        `[route modules] The file of namespace "${module.namespace}" must be a path inside the directory of the generated route tree, without extension; got "${file}".`,
      )
    }
    const clash = taken.get(file.toLowerCase())
    if (clash !== undefined) {
      throw new Error(
        `[route modules] The file of namespace "${module.namespace}" ("${file}") clashes with "${clash}". Generated files must differ in more than letter case; use another "routeScopeNamespaceFiles" layout.`,
      )
    }
    taken.set(file.toLowerCase(), file)
    files.set(module.key, file)
  }
  return files
}

/** An ESM namespace preserves products.Link without retaining unused APIs. */
export function buildRouteNamespaceSource(opts: {
  context: RouteModuleContext
  module: ScopeModule
  frameworkPackage: string
  routeTreeImport: string
  header: Array<string>
}) {
  const { context, module, frameworkPackage } = opts
  let router = routerTypeOf(module, context.identifiers)
  const hosted = module.hostedThrough !== undefined
  const lines = [
    ...opts.header,
    GENERATED_NOTICE,
    `import type { ScopedRouter${hosted ? ', HostedRouter' : ''} } from '${frameworkPackage}'`,
    ...contractTypeImports([module], context.identifiers),
  ]
  if (module.hostedThrough !== undefined) {
    lines.push(
      `import type { MountedModuleHostParams } from '${opts.routeTreeImport}'`,
    )
    router = `HostedRouter<${router}, ${hostParamsOf(module as ScopeModule & { hostedThrough: string }, context.identifiers)}>`
  }
  lines.push(
    `type Router = ScopedRouter<${router}, '${module.key}'>`,
    ...scopeBindings(frameworkPackage, 'Router', module.key),
    ...scopeMatchGuard(frameworkPackage, 'Router', module.matchRoots),
  )
  return lines.join('\n\n') + '\n'
}

/** Source of routeScope.gen.ts; each runtime API is an independent ESM export. */
export function buildRouteScopeSource(opts: {
  context: RouteModuleContext
  frameworkPackage: string
  routeTreeImport: string
  /** Import specifier of `routeContract.gen.ts`, which declares the module's register and router. */
  contractImport: string
  /** Root ids of the module and of every module it installs. */
  matchRoots: Array<string>
  namespaceImport: (module: ScopeModule) => string
  header: Array<string>
}): string {
  const { context, frameworkPackage } = opts
  const { declaration } = context
  const lines: Array<string> = [...opts.header, GENERATED_NOTICE]
  if (declaration.mode === 'module') {
    const moduleId = declaration.moduleId!
    const start = context.start
    // The register and router types live in the contract, which never
    // imports this file: the namespaces re-exported below reach the contracts
    // of used modules, and a module's contract must not.
    lines.push(
      `import { bindCreateModuleRoot } from '${frameworkPackage}/_internal/route-module'`,
      `import { createFileRoute as createFrameworkFileRoute } from '${frameworkPackage}'`,
      `import type { FileRouteScope } from '${frameworkPackage}'`,
      `import type { FileRoutesByPath } from '${opts.routeTreeImport}'`,
      `import type { RouteModuleRouter, RouteModuleRegister } from '${opts.contractImport}'`,
      `export type { RouteModuleRouter, RouteModuleRegister } from '${opts.contractImport}'`,
    )
    if (start) {
      lines.push(
        `import { createServerFn as createStartServerFn, createMiddleware as createStartMiddleware } from '${start.package}'`,
        `import { createStartModule as createStartModuleFor } from '${start.package}/_internal/route-module'`,
        `import type { CreateServerFn, CreateMiddlewareFn, StartModuleRegister } from '${start.package}'`,
      )
    }
    lines.push(
      `export const createFileRoute = createFrameworkFileRoute as FileRouteScope<FileRoutesByPath, RouteModuleRegister, '${moduleId}'>['createFileRoute']`,
      `export const createModuleRoot = /* @__PURE__ */ bindCreateModuleRoot<RouteModuleRegister, '${moduleId}'>('${moduleId}')`,
      ...scopeBindings(frameworkPackage, 'RouteModuleRouter', moduleId),
      ...scopeMatchGuard(
        frameworkPackage,
        'RouteModuleRouter',
        opts.matchRoots,
      ),
    )
    if (start) {
      lines.push(
        `export const createServerFn = createStartServerFn as unknown as CreateServerFn<RouteModuleRegister>`,
        `export const createMiddleware = createStartMiddleware as unknown as CreateMiddlewareFn<StartModuleRegister<'${moduleId}'>>`,
        `export const createStartModule = /* @__PURE__ */ createStartModuleFor('${moduleId}')`,
      )
    }
  }
  for (const module of context.scope) {
    lines.push(
      `export * as ${module.namespace} from '${opts.namespaceImport(module)}'`,
    )
  }
  if (declaration.mode === 'host' && context.scope.length === 0) {
    lines.push('export {}')
  }
  return lines.join('\n\n') + '\n'
}

/**
 * Source of `routeContract.gen.ts`: the public type entry of a module. It
 * declares the module's register and router, so the emitted declarations of
 * the route files reach this file, the route tree, the framework and the
 * contracts of included modules, and nothing of the modules the module uses.
 */
export function buildRouteContractSource(opts: {
  context: RouteModuleContext
  frameworkPackage: string
  routeTreeImport: string
  /** Import specifier of the module's Start file. */
  startImport: string
  header: Array<string>
}): string {
  const { context } = opts
  const moduleId = context.declaration.moduleId!
  const start = context.start
  const mounted = context.mounts.map((mount) => ({
    mount,
    identifier: getModuleIdentifier(mount.moduleId, context.identifiers),
  }))
  const lines: Array<string> = [...opts.header, GENERATED_NOTICE]
  lines.push(
    [
      `import type { ScopeRouter${
        context.mounts.some((mount) => mount.as !== undefined)
          ? ', InstallationRoutesById'
          : ''
      } } from '${opts.frameworkPackage}'`,
      `import type { FileRoutesById, ${mounted.length ? 'MountedModuleHostParams, ' : ''}routeTree } from '${opts.routeTreeImport}'`,
      ...(start
        ? [
            `import type { StartModuleRegister${start.file ? ', StartModuleConfig' : ''} } from '${start.package}'`,
            ...(start.file
              ? [`import type { start } from '${opts.startImport}'`]
              : []),
          ]
        : []),
      // The host params of a mounted module's own installations are only
      // needed when it installs other modules.
      ...mounted.map(
        ({ mount, identifier }) =>
          `import type { ${mount.installed.length > 1 ? `InstalledHostParams as ${identifier}InstalledHostParams, ` : ''}InstalledRoutesById as ${identifier}InstalledRoutesById, InstalledRouters as ${identifier}InstalledRouters } from '${mount.moduleId}/route-types'`,
      ),
    ].join('\n'),
  )
  lines.push(
    `/** The router of "${moduleId}": module-local paths, qualified ids. */
export type RouteModuleRouter = ScopeRouter<typeof routeTree, '${moduleId}'>`,
    `/** The register of "${moduleId}": the scope its route factories and route-bound APIs are typed against. */
export interface RouteModuleRegister${start ? ` extends StartModuleRegister<'${moduleId}'>` : ''} {
  router: RouteModuleRouter${start ? `\n  ssr: true${start.file ? '\n  config: StartModuleConfig<typeof start>' : ''}` : ''}
}`,
  )
  const hostParams = mounted.flatMap(({ mount, identifier }) => {
    const above = `MountedModuleHostParams['${mount.key}']`
    return mount.installed.map((installed) =>
      installed.id === mount.moduleId
        ? `  '${mount.key}': ${above}`
        : `  '${installed.key}': ${above} & ${identifier}InstalledHostParams['${installed.key}']`,
    )
  })
  lines.push(
    `/** The route tree of "${moduleId}": its module root with all its routes. */
export type RouteModuleTree = typeof routeTree`,
    `/** The router type of "${moduleId}" (module-local paths, qualified ids). */
export type Router = RouteModuleRouter`,
    `/** The routes of "${moduleId}" by qualified id, without other modules. */
export type OwnRoutesById = FileRoutesById`,
    `/** All routes installed with "${moduleId}", including the modules it mounts. */
export interface InstalledRoutesById extends FileRoutesById${mounted
      .map(({ mount, identifier }) =>
        mount.as === undefined
          ? `, ${identifier}InstalledRoutesById`
          : `, InstallationRoutesById<${identifier}InstalledRoutesById, '${mount.moduleId}', '${mount.as}'>`,
      )
      .join('')} {}`,
    // A named installation is keyed by its installation key, so the mounted
    // module's own entry is left out of what its contract contributes.
    `/** The routers of "${moduleId}" and of every module it mounts, by module id. */
export interface InstalledRouters${
      mounted.length
        ? ` extends ${mounted
            .map(({ mount, identifier }) =>
              mount.as === undefined
                ? `${identifier}InstalledRouters`
                : `Omit<${identifier}InstalledRouters, '${mount.moduleId}'>`,
            )
            .join(', ')}`
        : ''
    } {
  '${moduleId}': Router
${mounted.map(({ mount, identifier }) => `  '${mount.key}': ${identifier}InstalledRouters['${mount.moduleId}']`).join('\n')}
}`,
    `/**
 * The path params above every module "${moduleId}" installs, relative to its
 * root. Packages that mount "${moduleId}" under path params add their own.
 */
export interface InstalledHostParams {${hostParams.length ? `\n${hostParams.join('\n')}\n` : ''}}`,
  )
  return lines.join('\n\n') + '\n'
}

/** `.tanstack/route-types-stubs.d.ts`: stand-ins for the contracts of used modules. */
export function getRouteTypeStubsPath(packageRoot: string) {
  return path.join(packageRoot, '.tanstack', 'route-types-stubs.d.ts')
}

/**
 * Source of `.tanstack/route-types-stubs.d.ts`: an ambient stand-in for the
 * contract of every module this module uses. The declaration build includes
 * it and compiles against the stand-ins, so it needs no ordering against the
 * modules it links into; the source check does not include it and reads the
 * real contracts. An exact-name ambient module replaces the resolved file, so
 * a stand-in declares what generated code imports from a used contract
 * (`contractTypeImports`): the router, permissive enough for module-local
 * links, and the routers of the modules it installs.
 */
export function buildRouteTypeStubsSource(opts: {
  context: RouteModuleContext
  frameworkPackage: string
  header: Array<string>
}): string {
  const lines: Array<string> = [
    ...opts.header,
    GENERATED_NOTICE,
    `// Stand-ins for the contracts of the route modules this module uses. Include
// this file in the declaration build only (tsconfig.route-types.json): there it
// replaces the real contracts, so the build needs no ordering against the modules
// it links into. The source check (tsconfig.json) must not include it.`,
    ...opts.context.usedContracts.map(
      (id) => `declare module '${id}/route-types' {
  import type { AnyRoute, ScopeRouter } from '${opts.frameworkPackage}'
  export type Router = ScopeRouter<AnyRoute, '${id}'>
  export interface InstalledRouters {
    [key: string]: Router
  }
}`,
    ),
  ]
  return lines.join('\n\n') + '\n'
}

function startModulesImports(context: RouteModuleContext) {
  return context.startMounts.map((moduleId) => ({
    identifier: `${getModuleIdentifier(moduleId, context.identifiers)}StartModules`,
    statement: `import { startModules as ${getModuleIdentifier(moduleId, context.identifiers)}StartModules } from '${moduleId}/route-module'`,
  }))
}

/** Source of `routeModule.gen.ts`: the runtime entry includers import. */
export function buildRouteModuleSource(opts: {
  context: RouteModuleContext
  routeTreeImport: string
  /** Import specifier of the module's Start file. */
  startImport: string
  header: Array<string>
}): string {
  const { context } = opts
  const lines: Array<string> = [...opts.header, GENERATED_NOTICE]
  const mounted = startModulesImports(context)
  const ownFragment = context.exportsStartModules && !!context.start?.file
  if (context.exportsStartModules) {
    lines.push(
      [
        ...(ownFragment ? [`import { start } from '${opts.startImport}'`] : []),
        ...mounted.map((entry) => entry.statement),
      ].join('\n'),
    )
  }
  lines.push(
    `/** The root route of this module with all its routes. Mount it with \`mountRouteModule\`. */
export { routeTree as routeModule } from '${opts.routeTreeImport}'`,
  )
  if (context.exportsStartModules) {
    const entries = [
      ...mounted.map((entry) => `...${entry.identifier}`),
      ...(ownFragment ? ['start'] : []),
    ]
    const types = [
      ...mounted.map((entry) => `...typeof ${entry.identifier}`),
      ...(ownFragment ? ['typeof start'] : []),
    ]
    lines.push(
      `/**
 * The TanStack Start fragments of this module and of the modules it mounts.
 * Applications install them with \`createStart(() => ({ extends: startModules }))\`.
 */
export const startModules: readonly [${types.join(', ')}] = [${entries.join(', ')}]`,
    )
  }
  return lines.join('\n\n') + '\n'
}

/**
 * Source of an application's `startModules.gen.ts`: the Start fragments of
 * every installed route module, and a type check of the application's
 * Start instance against them.
 */
export function buildStartModulesSource(opts: {
  context: RouteModuleContext
  /** Import specifier of the application's Start file. */
  startImport: string
  header: Array<string>
}): string {
  const { context } = opts
  const mounted = startModulesImports(context)
  return (
    [
      ...opts.header,
      GENERATED_NOTICE,
      [
        `import type { AssertStartModules, ValidateStartModules } from '${context.start!.package}'`,
        ...(context.start!.file
          ? [`import type { startInstance } from '${opts.startImport}'`]
          : [`import type { StartInstance } from '${context.start!.package}'`]),
        ...mounted.map((entry) => entry.statement),
      ].join('\n'),
      `/**
 * The TanStack Start fragments of every installed route module. Install them
 * with \`createStart(() => ({ extends: startModules }))\`.
 */
export const startModules: readonly [${mounted
        .map((entry) => `...typeof ${entry.identifier}`)
        .join(', ')}] = [${mounted
        .map((entry) => `...${entry.identifier}`)
        .join(', ')}]`,
      ...(!context.start!.file
        ? [`type DefaultStartInstance = StartInstance<[], true, [], []>`]
        : []),
      `/**
 * Fails to type-check when \`startInstance\` does not install the fragments or
 * does not provide the context they require.
 */
export type StartModulesCheck = AssertStartModules<
  ValidateStartModules<${context.start!.file ? 'typeof startInstance' : 'DefaultStartInstance'}, typeof startModules, readonly [${[...new Set(context.mounts.flatMap((mount) => mount.manifest.modules.map((module) => module.id.split('#')[0]!)))].map((id) => `'${id}'`).join(', ')}]>
>`,
    ].join('\n\n') + '\n'
  )
}
