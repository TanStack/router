/** `@acme/user-account` -> `AcmeUserAccount` */
export function getModuleIdentifier(
  moduleId: string,
  identifiers?: Map<string, string>,
): string {
  const allocated = identifiers?.get(moduleId)
  if (allocated) {
    return allocated
  }
  const identifier = moduleId
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0]!.toUpperCase() + part.slice(1))
    .join('')
  return /^[0-9]/.test(identifier) ? `_${identifier}` : identifier || 'Module'
}

/** Variable of a mounted module root in a generated route tree. */
export function getMountVariableName(
  moduleId: string,
  identifiers?: Map<string, string>,
) {
  return `${getModuleIdentifier(moduleId, identifiers)}Module`
}

const GENERATED_NOTICE = `// This file was automatically generated by TanStack Router.
// You should NOT make any changes in this file as it will be overwritten.
// Additionally, you should also exclude this file from your linter and/or formatter to prevent it from being checked or modified.`

function routerTypeOf(module: ScopeModule, identifiers: Map<string, string>) {
  const identifier = getModuleIdentifier(module.contractPackage, identifiers)
  return module.contractPackage === module.moduleId
    ? `${identifier}Router`
    : `${identifier}InstalledRouters['${module.key}']`
}

/**
 * The path params above a hosted module (`ScopeModule.hostedThrough`): those
 * of this package's routes above the module it mounts, and the ones inside
 * that module's tree for a module it installs.
 */
function hostParamsOf(
  module: ScopeModule & { hostedThrough: string },
  identifiers: Map<string, string>,
) {
  const mounted = `MountedModuleHostParams['${module.hostedThrough}']`
  return module.hostedThrough === module.key
    ? mounted
    : `${mounted} & ${getModuleIdentifier(module.contractPackage, identifiers)}InstalledHostParams['${module.key}']`
}

function contractTypeImports(
  scope: Array<ScopeModule>,
  identifiers: Map<string, string>,
) {
  const byPackage = new Map<string, Set<string>>()
  const add = (pkg: string, name: string) => {
    const names = byPackage.get(pkg) ?? new Set<string>()
    names.add(name)
    byPackage.set(pkg, names)
  }
  for (const module of scope) {
    const identifier = getModuleIdentifier(module.contractPackage, identifiers)
    add(
      module.contractPackage,
      module.contractPackage === module.moduleId
        ? `Router as ${identifier}Router`
        : `InstalledRouters as ${identifier}InstalledRouters`,
    )
    if (
      module.hostedThrough !== undefined &&
      module.hostedThrough !== module.key
    ) {
      add(
        module.contractPackage,
        `InstalledHostParams as ${identifier}InstalledHostParams`,
      )
    }
  }
  return [...byPackage.entries()].map(
    ([pkg, names]) =>
      `import type { ${[...names].join(', ')} } from '${pkg}/route-types'`,
  )
}

