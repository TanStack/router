import { join } from 'pathe'
import { formatListenBanner, listenBannerRuntimeJs } from './listen-urls'

export type BunFetchHandler = (req: Request) => Response | Promise<Response>

/**
 * Map a request pathname to a file under the client output directory.
 * Returns null when the path should fall through to the SSR handler.
 */
export function resolveClientAssetPath(
  clientOutDir: string,
  pathname: string,
): string | null {
  let decoded: string
  try {
    decoded = decodeURIComponent(pathname)
  } catch {
    return null
  }
  if (!decoded.startsWith('/assets/') && !/\.\w+$/.test(decoded)) {
    return null
  }
  // Prevent path traversal
  const relative = decoded.replace(/^\//, '')
  if (relative.includes('..')) {
    return null
  }
  return join(clientOutDir, relative)
}

/**
 * Try to serve a static file from clientOutDir; otherwise null.
 */
export async function tryServeClientAsset(
  clientOutDir: string,
  pathname: string,
): Promise<Response | null> {
  const assetPath = resolveClientAssetPath(clientOutDir, pathname)
  if (!assetPath) {
    return null
  }
  const file = Bun.file(assetPath)
  if (!(await file.exists())) {
    return null
  }
  return new Response(file)
}

export interface StaticThenFetchOptions {
  clientOutDir: string
  fetch: BunFetchHandler
}

/**
 * Production / shared fetch: static assets first, then SSR handler.
 */
export function createStaticThenFetch(
  opts: StaticThenFetchOptions,
): BunFetchHandler {
  return async (req) => {
    const url = new URL(req.url)
    const staticResponse = await tryServeClientAsset(
      opts.clientOutDir,
      url.pathname,
    )
    if (staticResponse) {
      return staticResponse
    }
    return opts.fetch(req)
  }
}

export interface BunProdServeOptions {
  clientOutDir: string
  serverOutDir: string
  port?: number
  hostname?: string
}

/**
 * Production Bun.serve wrapping dist/server/server.js + dist/client.
 */
export async function createBunProdServer(opts: BunProdServeOptions): Promise<{
  stop: () => void
  port: number
  hostname: string
}> {
  const { pathToFileURL } = await import('node:url')
  const serverEntry = join(opts.serverOutDir, 'server.js')
  const handlerModule = (await import(pathToFileURL(serverEntry).href)) as {
    default?: { fetch?: BunFetchHandler }
  }
  const handlerFetch = handlerModule.default?.fetch
  if (!handlerFetch) {
    throw new Error(
      `[tanstack-start-bun] Server entry ${serverEntry} missing default.fetch`,
    )
  }
  const fetch = createStaticThenFetch({
    clientOutDir: opts.clientOutDir,
    fetch: (req) => handlerFetch(req),
  })

  const hostname = opts.hostname ?? '0.0.0.0'
  const server = Bun.serve({
    port: opts.port ?? 3000,
    hostname,
    fetch,
  })

  console.info(
    formatListenBanner({
      headline: '[tanstack-start-bun] serve',
      hostname,
      port: Number(server.port),
    }),
  )

  return {
    port: Number(server.port),
    hostname,
    stop() {
      server.stop(true)
    },
  }
}

