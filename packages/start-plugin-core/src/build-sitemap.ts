import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { createLogger } from './utils'
import type { TanStackStartOutputConfig } from './schema'

export type SitemapUrl = {
  loc: string
  lastmod: string
  priority?: number
  changefreq?:
    | 'always'
    | 'hourly'
    | 'daily'
    | 'weekly'
    | 'monthly'
    | 'yearly'
    | 'never'
  alternateRefs?: Array<{
    href: string
    hreflang?: string
  }>
  images?: Array<{
    loc: string
    title?: string
    caption?: string
  }>
  news?: {
    publication: {
      name: string
      language: string
    }
    publicationDate: string | Date
    title: string
  }
}

export type SitemapData = {
  urls: Array<SitemapUrl>
}

function buildSitemapJson(
  pages: TanStackStartOutputConfig['pages'],
  host: string,
): SitemapData {
  const slash = checkSlash(host)

  const urls: Array<SitemapUrl> = pages
    .filter((page) => {
      return page.sitemap?.exclude !== true
    })
    .map((page) => ({
      loc: `${host}${slash}${page.path.replace(/^\/+/g, '')}`,
      lastmod: page.sitemap?.lastmod
        ? new Date(page.sitemap.lastmod).toISOString().split('T')[0]!
        : new Date().toISOString().split('T')[0]!,
      priority: page.sitemap?.priority,
      changefreq: page.sitemap?.changefreq,
      alternateRefs: page.sitemap?.alternateRefs,
      images: page.sitemap?.images,
      news: page.sitemap?.news,
    }))

  return { urls }
}

function jsonToXml(sitemapData: SitemapData): string {
  const lines = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">',
    '  <!--This file was automatically generated by TanStack Start.-->',
  ]

  for (const item of sitemapData.urls) {
    lines.push('  <url>')
    lines.push(textElement(2, 'loc', item.loc))
    lines.push(textElement(2, 'lastmod', item.lastmod))

    if (item.priority !== undefined) {
      lines.push(textElement(2, 'priority', item.priority.toString()))
    }
    if (item.changefreq) {
      lines.push(textElement(2, 'changefreq', item.changefreq))
    }

    // Add alternate references
    if (item.alternateRefs?.length) {
      for (const ref of item.alternateRefs) {
        const hreflang = ref.hreflang
          ? ` hreflang="${escapeXml(ref.hreflang, true)}"`
          : ''
        lines.push(
          `    <xhtml:link rel="alternate" href="${escapeXml(ref.href, true)}"${hreflang} />`,
        )
      }
    }

    // Add images
    // The image and news prefixes are not declared on <urlset>, so their
    // elements reset the default namespace.
    if (item.images?.length) {
      for (const image of item.images) {
        lines.push('    <image:image xmlns="">')
        lines.push(textElement(3, 'image:loc', image.loc))
        if (image.title) {
          lines.push(textElement(3, 'image:title', image.title))
        }
        if (image.caption) {
          lines.push(textElement(3, 'image:caption', image.caption))
        }
        lines.push('    </image:image>')
      }
    }

    // Add news
    if (item.news) {
      lines.push('    <news:news xmlns="">')
      lines.push('      <news:publication>')
      lines.push(textElement(4, 'news:name', item.news.publication.name))
      lines.push(
        textElement(4, 'news:language', item.news.publication.language),
      )
      lines.push('      </news:publication>')
      lines.push(
        textElement(
          3,
          'news:publication_date',
          new Date(item.news.publicationDate).toISOString().split('T')[0]!,
        ),
      )
      lines.push(textElement(3, 'news:title', item.news.title))
      lines.push('    </news:news>')
    }

    lines.push('  </url>')
  }

  lines.push('</urlset>')
  return lines.join('\n')
}

function textElement(depth: number, name: string, text: string): string {
  const indent = '  '.repeat(depth)
  return text
    ? `${indent}<${name}>${escapeXml(text)}</${name}>`
    : `${indent}<${name}/>`
}

function escapeXml(value: string, attribute = false): string {
  // Ampersands that already start an entity are left untouched.
  const escaped = value
    .replace(/&(?![A-Za-z]+;|#\d+;)/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
  return attribute ? escaped.replace(/"/g, '&quot;') : escaped
}

export function buildSitemap({
  startConfig,
  publicDir,
}: {
  startConfig: TanStackStartOutputConfig
  publicDir: string
}) {
  const logger = createLogger('sitemap')

  let sitemapOptions = startConfig.sitemap

  if (!sitemapOptions && startConfig.pages.length) {
    sitemapOptions = { enabled: true, outputPath: 'sitemap.xml' }
  }

  if (!sitemapOptions?.enabled) {
    throw new Error('Sitemap is not enabled')
  }

  const { host, outputPath } = sitemapOptions

  if (!host) {
    if (!startConfig.sitemap) {
      logger.info(
        'Hint: Pages found, but no sitemap host has been set. To enable sitemap generation, set the `sitemap.host` option.',
      )
      return
    }
    throw new Error(
      'Sitemap host is not set and required to build the sitemap.',
    )
  }

  if (!outputPath) {
    throw new Error('Sitemap output path is not set')
  }

  const { pages } = startConfig

  if (!pages.length) {
    logger.info('No pages were found to build the sitemap. Skipping...')
    return
  }

  logger.info('Building Sitemap...')

  // Build the sitemap data
  const sitemapData = buildSitemapJson(pages, host)

  // Generate output paths
  const xmlOutputPath = path.join(publicDir, outputPath)
  const pagesOutputPath = path.join(publicDir, 'pages.json')

  try {
    // Write XML sitemap
    logger.info(`Writing sitemap XML at ${xmlOutputPath}`)
    writeFileSync(xmlOutputPath, jsonToXml(sitemapData))

    // Write pages data for runtime use
    logger.info(`Writing pages data at ${pagesOutputPath}`)
    writeFileSync(
      pagesOutputPath,
      JSON.stringify(
        {
          pages,
          host,
          lastBuilt: new Date().toISOString(),
        },
        null,
        2,
      ),
    )
  } catch (e) {
    logger.error(`Unable to write sitemap files`, e)
  }
}

function checkSlash(host: string): string {
  const finalChar = host.slice(-1)
  return finalChar === '/' ? '' : '/'
}
